-- drop user
drop user rcis;

-- create user
create user rcis identified by Changeme0;

-- grant basic permissions
grant create session to rcis;
grant create table, create view to rcis;
alter user rcis quota unlimited on users;

-- switch to user
alter session set current_schema = rcis;

-- create tables
create table role (
     id              number(19,0) generated by default as identity
    ,role            varchar2(128)
    ,description     varchar2(64)
);

create table login (
     id               number(19,0) generated by default as identity
    ,username         varchar2(16)
    ,password         varchar2(64)
    ,role_id          number(19,0)
    ,last_login_date  timestamp null
);

create table person (
     id               number(19,0) generated by default as identity
    ,first_name       varchar2(16)
    ,middle_name      varchar2(16)
    ,last_name        varchar2(64)
    ,email            varchar2(128)
    ,date_of_birth    date
    ,gender           varchar2(16)
    ,address          varchar2(255)
    ,contact_number   varchar2(16)
    ,login_id         number(19,0)
);

create table student (
    student_id         number(19,0) generated by default as identity
    ,person_id         number(19,0) not null
    ,student_number    varchar2(20)
    ,academic_level    varchar2(30)
    ,year_level        varchar2(20)
    ,section_id        number(19,0)
);

create table staff (
    staff_id           number(19,0) generated by default as identity
    ,person_id         number(19,0) not null
    ,staff_number      varchar2(20) not null
    ,position          varchar2(50) not null
    ,department        varchar2(100)
);

create table medical_record (
    medical_record_id  number(19,0) generated by default as identity
    ,student_id        number(19,0) not null
    ,medical_conditions varchar2(4000)
);

create table referral (
    referral_id        number(19,0) generated by default as identity
    ,student_id        number(19,0) not null
    ,medical_record_id  number(19,0) not null
    ,staff_id           number(19,0) not null
    ,referred_to        varchar2(50)
    ,referral_date      timestamp
    ,reason             varchar2(4000)
    ,status             varchar2(20)
);

-- create table constraints
alter table role
    add constraint ROLE_PK
        primary key (id);

alter table login
    add constraint LOGIN_PK
        primary key (id);

alter table person
    add constraint PERSON_PK
        primary key (id);

alter table login
    add constraint LOGIN_ROLE_FK
        foreign key (role_id)
            references role (id);

alter table person
    add constraint PERSON_LOGIN_FK
        foreign key (login_id)
            references login (id);

alter table student
    add constraint STUDENT_PK
        primary key (student_id);

alter table student
    add constraint STUDENT_PERSON_UQ
        unique (person_id);

alter table student
    add constraint STUDENT_NUMBER_UQ
        unique (student_number);

alter table student
    add constraint STUDENT_PERSON_FK
        foreign key (person_id)
            references person (id);

alter table student
    add constraint STUDENT_ACADEMIC_LEVEL_CK
        check (academic_level in ('Junior High School', 'Senior High School', 'College'));

alter table staff
    add constraint STAFF_PK
        primary key (staff_id);

alter table staff
    add constraint STAFF_PERSON_UQ
        unique (person_id);

alter table staff
    add constraint STAFF_NUMBER_UQ
        unique (staff_number);

alter table staff
    add constraint STAFF_PERSON_FK
         foreign key (person_id)
            references person (id) ;

alter table medical_record
    add constraint MEDICAL_RECORD_PK
          primary key (medical_record_id);

alter table medical_record
    add constraint MEDICAL_RECORD_STUDENT_UQ
        unique (student_id);

alter table medical_record
    add constraint MEDICAL_RECORD_STUDENT_FK
        foreign key (student_id)
            references student(student_id);

alter table referral
    add constraint REFERRAL_PK
        primary key (referral_id);

alter table referral
    add constraint REFERRAL_STUDENT_FK
        foreign key (student_id)
            references student(student_id);

alter table referral
    add constraint REFERRAL_MEDICAL_RECORD_FK
        foreign key (medical_record_id)
            references medical_record(medical_record_id);

alter table referral
    add constraint REFERRAL_STAFF_FK
        foreign key (staff_id)
            references staff(staff_id);

alter table referral
    add constraint REFERRAL_STATUS_CK
        check (status in ('Pending', 'Completed'));

