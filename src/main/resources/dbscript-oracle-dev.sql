-- create tables
create table role (
     id              number(19,0) generated by default as identity
    ,role            varchar2(128)
    ,description     varchar2(64)
);

create table login (
     id               number(19,0) generated by default as identity
    ,username         varchar2(16)
    ,password         varchar2(64)
    ,role_id          number(19,0)
    ,last_login_date  timestamp null
);

create table person (
     id               number(19,0) generated by default as identity
    ,first_name       varchar2(16)
    ,middle_name      varchar2(16)
    ,last_name        varchar2(64)
    ,email            varchar2(128)
    ,date_of_birth    date
    ,gender           varchar2(16)
    ,address          varchar2(255)
    ,contact_number   varchar2(16)
    ,login_id         number(19,0)
);

create table department (
     department_id        number(19,0) generated by default as identity
    ,department_name      varchar2(100) not null
);

create table personnel_position (
     position_id          number(19,0) generated by default as identity
    ,position_name        varchar2(100) not null
    ,category             varchar2(20) not null
    ,office               varchar2(100)
);

create table personnel (
     personnel_id         number(19,0) generated by default as identity
    ,person_id            number(19,0) not null
    ,personnel_number     varchar2(30) not null
    ,position_id          number(19,0) not null
);

create table adviser (
     adviser_id           number(19,0) generated by default as identity
    ,personnel_id         number(19,0) not null
    ,adviser_number       varchar2(20) not null
);

create table school_year (
     school_year_id       number(19,0) generated by default as identity
    ,school_year_name     varchar2(20) not null
    ,start_date           date not null
    ,end_date             date not null
);

create table year_level (
     year_level_id        number(19,0) generated by default as identity
    ,department_id        number(19,0) not null
    ,year_level_name      varchar2(30) not null
);

create table section (
     section_id           number(19,0) generated by default as identity
    ,section_name         varchar2(50) not null
    ,year_level_id        number(19,0) not null
    ,adviser_id           number(19,0)
    ,school_year_id       number(19,0) not null
);

create table student (
     student_id           number(19,0) generated by default as identity
    ,person_id            number(19,0) not null
    ,student_number       varchar2(30) not null
    ,section_id           number(19,0)
);

create table staff (
     staff_id             number(19,0) generated by default as identity
    ,person_id            number(19,0) not null
    ,staff_number         varchar2(30) not null
    ,position             varchar2(50) not null
);

create table medical_record (
     medical_record_id    number(19,0) generated by default as identity
    ,person_id            number(19,0) not null
    ,medical_conditions   varchar2(4000)
    ,allergies            varchar2(4000)
);

create table consultation (
     consultation_id      number(19,0) generated by default as identity
    ,medical_record_id    number(19,0) not null
    ,patient_id           number(19,0) not null
    ,staff_id             number(19,0) not null
    ,record_type          varchar2(50) not null
    ,consultation_date    timestamp not null
    ,complaint            varchar2(4000)
    ,diagnosis            varchar2(4000) not null
    ,treatment            varchar2(4000) not null
    ,action_taken         varchar2(4000)
    ,remarks              varchar2(4000)
);

create table medicine_category (
     category_id          number(19,0) generated by default as identity
    ,category_name        varchar2(100) not null
);

create table medicine (
     medicine_id          number(19,0) generated by default as identity
    ,medicine_name        varchar2(100) not null
    ,category_id          number(19,0)
    ,unit                 varchar2(30) not null
);

create table inventory (
     item_id              number(19,0) generated by default as identity
    ,medicine_id          number(19,0) not null
    ,staff_id             number(19,0) not null
    ,batch_number         varchar2(50)
    ,stock_quantity       number(10,0) default 0 not null
    ,expiration_date      date
);

create table prescription (
     prescription_id      number(19,0) generated by default as identity
    ,consultation_id      number(19,0) not null
    ,item_id              number(19,0) not null
    ,staff_id             number(19,0) not null
    ,quantity_to_dispense number(19,0) not null
    ,dose                 varchar2(100) not null
    ,frequency            varchar2(100) not null
    ,duration             varchar2(100)
    ,instructions         varchar2(4000)
);

