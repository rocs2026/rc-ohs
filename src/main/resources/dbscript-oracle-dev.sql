select
    medicine_name,
    stock_quantity,
    minimum_stock_level
from inventory_view
where stock_quantity <= minimum_stock_level;

select
    medicine_name,
    batch_number,
    expiration_date
from inventory_view
where expiration_date < trunc(sysdate);

select
    medicine_name,
    batch_number,
    expiration_date
from inventory_view
where expiration_date between trunc(sysdate)
          and trunc(sysdate) + 30;

select
    medicine_name,
    sum(stock_quantity) as total_stock
from inventory_view
group by medicine_name;

