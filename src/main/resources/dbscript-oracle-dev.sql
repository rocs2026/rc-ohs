create or replace view inventory_view as
select
    i.item_id,
    m.medicine_id,
    m.medicine_name,
    m.category,
    m.unit,
    i.batch_number,
    i.stock_quantity,
    i.minimum_stock_level,
    i.expiration_date,
    s.staff_id,
    s.staff_number,
    s.position,
    s.department,
    p.first_name,
    p.last_name
from inventory i
         join medicine m
              on i.medicine_id = m.medicine_id
         join staff s
              on i.staff_id = s.staff_id
         join person p
              on s.person_id = p.person_id;

