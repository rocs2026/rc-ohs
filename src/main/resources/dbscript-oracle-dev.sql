-- create tables
create table role (
     id              number(19,0) generated by default as identity
    ,role            varchar2(128)
    ,description     varchar2(64)
);

create table login (
     id               number(19,0) generated by default as identity
    ,username         varchar2(16)
    ,password         varchar2(64)
    ,role_id          number(19,0)
    ,last_login_date  timestamp null
);

create table person (
     id               number(19,0) generated by default as identity
    ,first_name       varchar2(16)
    ,middle_name      varchar2(16)
    ,last_name        varchar2(64)
    ,email            varchar2(128)
    ,date_of_birth    date
    ,gender           varchar2(16)
    ,address          varchar2(255)
    ,contact_number   varchar2(16)
    ,login_id         number(19,0)
);

create table staff (
    staff_id         number(19,0) generated by default as identity
    ,person_id       number(19,0) not null
    ,staff_number    varchar2(30) not null
    ,position        varchar2(50) not null
    ,department      varchar2(100)
);

create table student (
    student_id       number(19,0) generated by default as identity
    ,person_id       number(19,0) not null
    ,student_number  varchar2(30) not null
    ,academic_level  varchar2(50)
    ,year_level      varchar2(30)
    ,section_id      number(19,0)
);

create table medical_record (
    medical_record_id number(19,0) generated by default as identity
    ,student_id      number(19,0) not null
    ,medical_conditions varchar2(4000)
);

create table consultation (
    consultation_id  number(19,0) generated by default as identity
    ,medical_record_id number(19,0) not null
    ,staff_id        number(19,0) not null
    ,record_type     varchar2(50)
    ,consultation_date timestamp not null
    ,complaint       varchar2(4000)
    ,diagnosis       varchar2(4000) not null
    ,treatment       varchar2(4000) not null
    ,action_taken    varchar2(4000)
    ,remarks         varchar2(4000)
);

create table medicine (
    medicine_id      number(19,0) generated by default as identity
    ,medicine_name   varchar2(100) not null
    ,category        varchar2(100)
    ,unit            varchar2(30) not null
);

create table inventory (
    item_id          number(19,0) generated by default as identity
    ,medicine_id     number(19,0) not null
    ,staff_id         NUMBER(19,0) not null
    ,batch_number    varchar2(50)
    ,stock_quantity  number(10,0) default 0 not null
    ,expiration_date date
);

create table prescription (
    prescription_id  number(19,0) generated by default as identity
    ,consultation_id number(19,0) not null
    ,item_id         number(19,0) not null
    ,staff_id        number(19,0) not null
    ,medication_quantity number(10,0) not null
    ,dosage          varchar2(100) not null
    ,frequency       varchar2(100) not null
    ,duration        varchar2(100)
    ,instructions    varchar2(4000)
);

-- create table constraints
alter table role
    add constraint ROLE_PK
        primary key (id);

alter table login
    add constraint LOGIN_PK
        primary key (id);

alter table person
    add constraint PERSON_PK
        primary key (id);

alter table login
    add constraint LOGIN_ROLE_FK
        foreign key (role_id)
            references role (id);

alter table person
    add constraint PERSON_LOGIN_FK
        foreign key (login_id)
            references login (id);

alter table staff
    add constraint STAFF_PK
        primary key (staff_id);

alter table staff
    add constraint STAFF_PERSON_UQ
        unique (person_id);

alter table staff
    add constraint STAFF_NUMBER_UQ
        unique (staff_number);

alter table staff
    add constraint STAFF_PERSON_FK
        foreign key (person_id)
            references person (id);

alter table student
    add constraint STUDENT_PK
        primary key (student_id);

alter table student
    add constraint STUDENT_PERSON_UQ
        unique (person_id);

alter table student
    add constraint STUDENT_NUMBER_UQ
        unique (student_number);

alter table student
    add constraint STUDENT_PERSON_FK
        foreign key (person_id)
            references person (id);

alter table medical_record
    add constraint MEDICAL_RECORD_PK
        primary key (medical_record_id);

alter table medical_record
    add constraint MEDICAL_RECORD_STUDENT_UQ
        unique (student_id);

alter table medical_record
    add constraint MEDICAL_RECORD_STUDENT_FK
        foreign key (student_id)
            references student (student_id);

alter table consultation
    add constraint CONSULTATION_PK
        primary key (consultation_id);

alter table consultation
    add constraint CONSULTATION_RECORD_FK
        foreign key (medical_record_id)
            references medical_record (medical_record_id);

alter table consultation
    add constraint CONSULTATION_STAFF_FK
        foreign key (staff_id)
            references staff (staff_id);

alter table medicine
    add constraint MEDICINE_PK
        primary key (medicine_id);

alter table inventory
    add constraint INVENTORY_PK
        primary key (item_id);

alter table inventory
    add constraint INVENTORY_STOCK_CK
        check (stock_quantity >= 0);

alter table inventory
    add constraint INVENTORY_MEDICINE_FK
        foreign key (medicine_id)
            references medicine (medicine_id);

alter table inventory
    add constraint INVENTORY_STAFF_FK
        foreign key (staff_id)
            references staff (staff_id);

alter table prescription
    add constraint PRESCRIPTION_PK
        primary key (prescription_id);

alter table prescription
    add constraint PRESCRIPTION_QTY_CK
        check (medication_quantity > 0);

alter table prescription
    add constraint PRESCRIPTION_CONSULTATION_FK
        foreign key (consultation_id)
            references consultation (consultation_id);

alter table prescription
    add constraint PRESCRIPTION_ITEM_FK
        foreign key (item_id)
            references inventory (item_id);

alter table prescription
    add constraint PRESCRIPTION_STAFF_FK
        foreign key (staff_id)
            references staff (staff_id);

