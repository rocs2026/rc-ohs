alter session set current_schema = rcis;

-- drp db objects
drop table role;
drop table login;
drop table person;

-- create tables

CREATE TABLE student (
    student_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
        PRIMARY KEY,
    person_id NUMBER NOT NULL UNIQUE,
    student_number VARCHAR2(30) NOT NULL UNIQUE,
    academic_level VARCHAR2(50),
    year_level VARCHAR2(30),
    section_id NUMBER(10),
    CONSTRAINT fk_student_person
        FOREIGN KEY (person_id)
        REFERENCES person(person_id)
);

CREATE TABLE staff (
    staff_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
        PRIMARY KEY,
    person_id NUMBER NOT NULL UNIQUE,
    staff_number VARCHAR2(30) NOT NULL UNIQUE,
    position VARCHAR2(50) NOT NULL,
    department VARCHAR2(100),
    CONSTRAINT fk_staff_person
        FOREIGN KEY (person_id)
        REFERENCES person(person_id)
);

CREATE TABLE medical_record (
    medical_record_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
        PRIMARY KEY,
    student_id NUMBER NOT NULL UNIQUE,
    medical_conditions VARCHAR2(4000),
    CONSTRAINT fk_medical_record_student
        FOREIGN KEY (student_id)
        REFERENCES student(student_id)
);


create table role (
                      id              number(19,0)
    ,role           varchar2(128)
    ,description    varchar2(64)
);

create table login (
                       id              number(19,0)
    ,username       varchar2(16)
    ,password       varchar2(64)
    ,role_id        number(19,0)
    ,last_login_date timestamp
);

create table person (
                        id               number(19,0)
    ,first_name      varchar2(16)
    ,last_name       varchar2(64)
    ,login_id        number(19,0)
);

-- create table constraints
alter table role
    add constraint ROLE_PK
        primary key (id);

alter table login
    add constraint LOGIN_PK
        primary key (id);

alter table person
    add constraint PERSON_PK
        primary key (id);

alter table login
    add constraint LOGIN_ROLE_FK
        foreign key (role_id)
            references role (id);

alter table person
    add constraint PERSON_LOGIN_FK
        foreign key (login_id)
            references login (id);

