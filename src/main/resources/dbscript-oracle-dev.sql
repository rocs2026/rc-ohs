create table person (
                        person_id number generated by default as identity,
                        last_name varchar2(50),
                        first_name varchar2(50),
                        middle_name varchar2(50),
                        email varchar2(100),
                        date_of_birth date,
                        gender varchar2(20),
                        address varchar2(255),
                        contact_number varchar2(20),
                        constraint pk_person primary key (person_id)
);

create table staff (
                       staff_id number generated by default as identity,
                       person_id number not null,
                       staff_number varchar2(20) not null,
                       position varchar2(50),
                       department varchar2(100),
                       constraint pk_staff primary key (staff_id),
                       constraint uq_staff_person unique (person_id),
                       constraint uq_staff_number unique (staff_number),
                       constraint fk_staff_person foreign key (person_id)
                           references person(person_id)
);

create table medicine (
                          medicine_id number generated by default as identity,
                          medicine_name varchar2(100) not null,
                          category varchar2(50),
                          unit varchar2(30),
                          constraint pk_medicine primary key (medicine_id)
);

create table inventory (
                           item_id number generated by default as identity,
                           medicine_id number not null,
                           staff_id number not null,
                           batch_number varchar2(50),
                           stock_quantity number(10) default 0 not null,
                           minimum_stock_level number(10) default 0 not null,
                           expiration_date date,
                           constraint pk_inventory primary key (item_id),
                           constraint fk_inventory_medicine foreign key (medicine_id)
                               references medicine(medicine_id),
                           constraint fk_inventory_staff foreign key (staff_id)
                               references staff(staff_id),
                           constraint chk_stock_quantity check (stock_quantity >= 0),
                           constraint chk_minimum_stock check (minimum_stock_level >= 0)
);

